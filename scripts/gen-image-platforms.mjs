#!/usr/bin/env node
// Emits src/app/image-gen/image-platforms.generated.ts from openapi.json.
//
// The admin BFF publishes BatchImageSpec.hardwareClass as an enum read from the
// generator worklist schema it vendors. ng-openapi-gen turns that inline enum
// into a type union only, so the image-gen wizard has no runtime list to offer.
// This script writes that list, in the BFF's order, next to the wizard.
//
// `npm run gen` runs it after ng-openapi-gen. With --check it writes nothing and
// exits 1 when the committed file differs from what openapi.json gives.
//
// It fails closed: a missing schema, a missing or empty enum, a non-string
// member, a duplicate, or a member outside a lower-case token of at most 32
// characters stops it before anything is written.
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const specPath = join(root, 'openapi.json');
const outPath = join(root, 'src/app/image-gen/image-platforms.generated.ts');
const TOKEN = /^[a-z0-9][a-z0-9-]{0,31}$/;

function fail(msg) {
  console.error(`gen-image-platforms: ${msg}`);
  process.exit(1);
}

let spec;
try {
  spec = JSON.parse(readFileSync(specPath, 'utf8'));
} catch (e) {
  fail(`cannot read ${specPath}: ${e.message}`);
}
const prop = spec?.components?.schemas?.BatchImageSpec?.properties?.hardwareClass;
if (!prop) fail('openapi.json has no components.schemas.BatchImageSpec.properties.hardwareClass');
const platforms = prop.enum;
if (!Array.isArray(platforms) || platforms.length === 0) {
  fail('BatchImageSpec.hardwareClass carries no enum: regenerate openapi.json from an admin-bff that publishes one');
}
const seen = new Set();
for (const p of platforms) {
  if (typeof p !== 'string' || !TOKEN.test(p)) fail(`platform ${JSON.stringify(p)} is not a lower-case token of at most 32 characters`);
  if (seen.has(p)) fail(`platform ${p} is listed twice`);
  seen.add(p);
}

const body = `/* Code generated by scripts/gen-image-platforms.mjs from openapi.json. DO NOT EDIT. */
/* Regenerate with \`npm run gen\` (or \`npm run gen:spec\`) after copying the admin-bff spec. */

/** Every platform the admin BFF accepts for a batch image (BatchImageSpec.hardwareClass enum),
 *  in the BFF's order. The BFF reads it from the generator worklist schema it vendors. */
export const SCHEMA_IMAGE_PLATFORMS = [
${platforms.map((p) => `  '${p}',`).join('\n')}
] as const;
`;

if (process.argv.includes('--check')) {
  let current = '';
  try {
    current = readFileSync(outPath, 'utf8');
  } catch {
    fail(`${outPath} is missing: run npm run gen`);
  }
  if (current !== body) fail(`${outPath} differs from openapi.json: run npm run gen`);
  console.log(`gen-image-platforms: ${platforms.length} platforms, generated file matches openapi.json`);
} else {
  writeFileSync(outPath, body);
  console.log(`gen-image-platforms: wrote ${platforms.length} platforms to ${outPath.slice(root.length + 1)}`);
}
